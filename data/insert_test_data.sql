-- 3 GENERATE 1850 EMPLOYEES WITH EXACTLY 350 INACTIVE
INSERT INTO BRONZE.EMPLOYEES_RAW
WITH BASE AS (
    SELECT
        SEQ4() + 1 AS EMPLOYEE_ID,
        ARRAY_CONSTRUCT(
            'JOHN','SARAH','MICHAEL','PRIYA','DAVID','EMILY','RAJ','AISHA','CARLOS','MARIA',
            'JAMES','LINDA','ROBERT','SOPHIA','DANIEL','OLIVIA','ETHAN','GRACE','ARJUN','NEHA'
        )[UNIFORM(0,19,RANDOM())] AS FIRST_NAME,
        ARRAY_CONSTRUCT(
            'DOE','LEE','SMITH','SHARMA','PATEL','JOHNSON','BROWN','GARCIA','MARTINEZ','SINGH',
            'KHAN','TAYLOR','ANDERSON','THOMAS','JACKSON','WHITE','HARRIS','CLARK','LEWIS','YOUNG'
        )[UNIFORM(0,19,RANDOM())] AS LAST_NAME,
        DATEADD(
            DAY,
            UNIFORM(0, 3650, RANDOM()),
            '2015-01-01'
        ) AS HIRE_DATE,
        UNIFORM(1,12,RANDOM()) AS DEPARTMENT_ID,
        ARRAY_CONSTRUCT(
            'SOFTWARE ENGINEER','SENIOR ENGINEER','HR SPECIALIST','DATA ANALYST',
            'MANAGER','DIRECTOR','QA ENGINEER','DEVOPS ENGINEER','PRODUCT OWNER'
        )[UNIFORM(0,8,RANDOM())] AS JOB_TITLE,
        ARRAY_CONSTRUCT(
            'SAN JOSE','TRACY','FREMONT','PLEASANTON','SACRAMENTO'
        )[UNIFORM(0,4,RANDOM())] AS LOCATION,
        100 + UNIFORM(0, 49, RANDOM()) AS SUPERVISOR_ID
    FROM TABLE(GENERATOR(ROWCOUNT => 1850))
),
TERMINATED AS (
    SELECT EMPLOYEE_ID
    FROM BASE
    QUALIFY ROW_NUMBER() OVER (ORDER BY EMPLOYEE_ID) <= 350
)
SELECT
    B.EMPLOYEE_ID,
    B.FIRST_NAME,
    B.LAST_NAME,
    LOWER(B.FIRST_NAME || '.' || B.LAST_NAME || '@COMPANY.COM') AS EMAIL,
    B.HIRE_DATE,
    CASE WHEN T.EMPLOYEE_ID IS NOT NULL THEN
        DATEADD(DAY, UNIFORM(30, 2000, RANDOM()), B.HIRE_DATE)
    ELSE NULL END AS TERMINATION_DATE,
    B.DEPARTMENT_ID,
    B.JOB_TITLE,
    B.LOCATION,
    CASE WHEN T.EMPLOYEE_ID IS NOT NULL THEN 'TERMINATED' ELSE 'ACTIVE' END AS STATUS,
    B.SUPERVISOR_ID
FROM BASE B
LEFT JOIN TERMINATED T USING (EMPLOYEE_ID);


-- 4. GENERATE JOB HISTORY
INSERT INTO BRONZE.JOB_HISTORY_RAW
SELECT
    EMPLOYEE_ID,
    ARRAY_CONSTRUCT(
        'INTERN','JUNIOR ENGINEER','ENGINEER','SENIOR ENGINEER','LEAD ENGINEER',
        'MANAGER','SENIOR MANAGER','DIRECTOR','VP'
    )[UNIFORM(0,8,RANDOM())] AS JOB_TITLE,
    HIRE_DATE AS START_DATE,
    CASE WHEN TERMINATION_DATE IS NOT NULL
        THEN TERMINATION_DATE
        ELSE DATEADD(YEAR, UNIFORM(1,5,RANDOM()), HIRE_DATE)
    END AS END_DATE
FROM BRONZE.EMPLOYEES_RAW;


-- 5. GENERATE EMPLOYEE STATUS
INSERT INTO BRONZE.EMPLOYEE_STATUS_RAW
SELECT
    EMPLOYEE_ID,
    STATUS AS EMPLOYMENT_STATUS,
    HIRE_DATE AS STATUS_EFFECTIVE_DATE,
    TERMINATION_DATE
FROM BRONZE.EMPLOYEES_RAW;


-- 6. GENERATE EMPLOYEE LOCATION
INSERT INTO BRONZE.EMPLOYEE_LOCATION_RAW
SELECT
    EMPLOYEE_ID,
    LOCATION AS WORK_LOCATION,
    HIRE_DATE AS EFFECTIVE_START_DATE,
    CASE WHEN TERMINATION_DATE IS NOT NULL
        THEN TERMINATION_DATE
        ELSE DATEADD(YEAR, 10, HIRE_DATE)
    END AS EFFECTIVE_END_DATE
FROM BRONZE.EMPLOYEES_RAW;
